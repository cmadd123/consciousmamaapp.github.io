// Creator Library uploader — uploads media to Firebase Storage (/creator_library/)
// and regenerates creator/library/manifest.js with rows for EVERY upload category.
//
// 1. Drop files into the staging folders (created on first run):
//      scripts/creator-library/appDemos/      → short no-audio app demos (video)
//      scripts/creator-library/bRoll/         → hands-only cooking B-roll (video)
//      scripts/creator-library/brandElements/ → downloadable assets (png/jpg/pdf/zip)
// 2. Run:
//      NODE_PATH=./admin/node_modules node scripts/upload-creator-library.js [service-account.json]
//      (defaults to admin/service-account.json; or pass the adminsdk json path)
// 3. Review the titles/durations it wrote, then:
//      git add creator/library/manifest.js && git commit -m "library: new assets" && git push
//
// Idempotent: re-running overwrites the Storage object + refreshes its URL (no dup rows).
// Videos get a probed duration (mp4 mvhd atom; null if it can't read it — edit by hand).
// `examples` (external Reels) + Canva-link brand elements + CAPTION_SNIPPETS are URLs/text,
// not file uploads — they're PRESERVED here and added by editing manifest.js directly.

const admin = require('firebase-admin');
const fs = require('fs');
const path = require('path');
const { pathToFileURL } = require('url');

const repoRoot = path.resolve(__dirname, '..');
const stageRoot = path.join(repoRoot, 'scripts', 'creator-library');
const manifestPath = path.join(repoRoot, 'creator', 'library', 'manifest.js');
const saPath = path.resolve(process.argv[2] || path.join(repoRoot, 'admin', 'service-account.json'));
const BUCKET = 'parenting-plus-7szrif.appspot.com';

const CATS = [
  ['appDemos', 'video'],
  ['bRoll', 'video'],
  ['brandElements', 'asset'],
];
const CONTENT_TYPE = {
  '.mp4': 'video/mp4', '.mov': 'video/quicktime', '.webm': 'video/webm', '.m4v': 'video/x-m4v',
  '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.gif': 'image/gif',
  '.pdf': 'application/pdf', '.zip': 'application/zip',
};

function titleFrom(name) {
  return path.basename(name, path.extname(name))
    .replace(/[-_]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/\b\w/g, (c) => c.toUpperCase());
}

// Best-effort mp4 duration (seconds) from the mvhd atom — no ffmpeg dependency.
function mp4Duration(file) {
  try {
    const buf = fs.readFileSync(file);
    const i = buf.indexOf(Buffer.from('mvhd'));
    if (i < 0) return null;
    const version = buf[i + 4];
    let timescale, duration;
    if (version === 1) {
      timescale = buf.readUInt32BE(i + 24);
      duration = Number(buf.readBigUInt64BE(i + 28));
    } else {
      timescale = buf.readUInt32BE(i + 16);
      duration = buf.readUInt32BE(i + 20);
    }
    return timescale ? Math.round(duration / timescale) : null;
  } catch {
    return null;
  }
}

function ensureStaging() {
  let made = false;
  for (const [cat] of CATS) {
    const d = path.join(stageRoot, cat);
    if (!fs.existsSync(d)) { fs.mkdirSync(d, { recursive: true }); made = true; }
  }
  return made;
}

function renderManifest(captions, M) {
  return `// Creator Library content manifest — GENERATED by scripts/upload-creator-library.js.
// To add media: drop files in scripts/creator-library/{appDemos,bRoll,brandElements}/
// and re-run the script. To add an external Reel example or a Canva-link brand
// element, or to edit captions, hand-edit the arrays below (they're preserved on re-run).
// The library page (index.html) reads these exports on load — no build step.

export const CAPTION_SNIPPETS = ${JSON.stringify(captions, null, 2)};

export const LIBRARY_MANIFEST = ${JSON.stringify(M, null, 2)};
`;
}

(async () => {
  if (ensureStaging()) {
    console.log('Created staging folders under scripts/creator-library/. Drop your files in and re-run:');
    for (const [cat, kind] of CATS) console.log(`  scripts/creator-library/${cat}/  (${kind})`);
    process.exit(0);
  }

  admin.initializeApp({ credential: admin.credential.cert(require(saPath)), storageBucket: BUCKET });
  const bucket = admin.storage().bucket();

  // Preserve existing manifest entries (captions, examples, external links).
  const existing = await import(pathToFileURL(manifestPath).href);
  const captions = existing.CAPTION_SNIPPETS || [];
  const M = Object.assign({ appDemos: [], bRoll: [], brandElements: [], examples: [] }, existing.LIBRARY_MANIFEST || {});
  for (const k of ['appDemos', 'bRoll', 'brandElements', 'examples']) M[k] = M[k] || [];
  const seen = new Set([...M.appDemos, ...M.bRoll, ...M.brandElements].map((e) => e.url).filter(Boolean));

  let added = 0, refreshed = 0;
  for (const [cat, kind] of CATS) {
    const dir = path.join(stageRoot, cat);
    if (!fs.existsSync(dir)) continue;
    for (const fname of fs.readdirSync(dir).sort()) {
      const lp = path.join(dir, fname);
      if (!fs.statSync(lp).isFile() || fname.startsWith('.')) continue;
      const ext = path.extname(fname).toLowerCase();
      const dest = `creator_library/${cat}/${fname}`;
      await bucket.upload(lp, {
        destination: dest,
        metadata: { contentType: CONTENT_TYPE[ext] || 'application/octet-stream', cacheControl: 'public, max-age=31536000, immutable' },
      });
      await bucket.file(dest).makePublic();
      const url = `https://storage.googleapis.com/${BUCKET}/${dest}`;
      if (seen.has(url)) { console.log(`  · ${cat}/${fname} (re-uploaded; already in manifest)`); refreshed++; continue; }
      if (kind === 'video') {
        M[cat].push({ url, title: titleFrom(fname), duration: mp4Duration(lp), note: '' });
      } else {
        M[cat].push({ title: titleFrom(fname), description: '', url, cta: 'Download' });
      }
      seen.add(url); added++;
      console.log(`  ✓ ${cat}/${fname}`);
    }
  }

  fs.writeFileSync(manifestPath, renderManifest(captions, M));
  console.log(`\nAdded ${added} new asset(s)${refreshed ? `, refreshed ${refreshed}` : ''}. Rewrote creator/library/manifest.js.`);
  console.log('Review titles/durations, then: git add creator/library/manifest.js && git commit && git push');
  process.exit(0);
})().catch((e) => { console.error(e); process.exit(1); });
